fn execute_edge_treatment(
    input: &EdgeTreatmentInput,
    profile: FilletProfile,
) -> Result<Solid, FeatureError> {
    let solid = decode_solid("target", &input.target)?;
    let mut boundaries = solid.into_boundaries();
    let mut found = std::collections::BTreeSet::new();
    for shell in &mut boundaries {
        let selected: Vec<_> = input
            .edge_stable_ids
            .iter()
            .filter_map(|stable_id| {
                shell
                    .edge_iter()
                    .find(|edge| edge.stable_id().raw() == *stable_id)
                    .inspect(|_| {
                        found.insert(*stable_id);
                    })
            })
            .collect();
        if selected.is_empty() {
            continue;
        }
        let options = FilletOptions {
            radius: RadiusSpec::Constant(model_units(input.radius_nm)),
            divisions: NonZeroUsize::new(input.divisions as usize).expect("validated non-zero"),
            profile: profile.clone(),
        };
        fillet_edges(shell, &selected, Some(&options)).map_err(|error| {
            unsupported_preserving(
                format!("pinned edge treatment rejected the selected topology: {error}"),
                "edge_stable_ids",
                &input.target,
                selected.first().map(|edge| ProblematicReference {
                    kind: ReferenceKind::Edge,
                    stable_id: edge.stable_id().raw().to_string(),
                    ordered_index: input
                        .edge_stable_ids
                        .iter()
                        .position(|id| *id == edge.stable_id().raw()),
                }),
            )
        })?;
    }
    if let Some((index, missing)) = input
        .edge_stable_ids
        .iter()
        .enumerate()
        .find(|(_, id)| !found.contains(id))
    {
        let mut error = invalid(
            "edge_stable_ids",
            "contains a reference absent from the target",
        );
        error.preserved_inputs.push(input.target.clone());
        error.problematic_reference = Some(Box::new(ProblematicReference {
            kind: ReferenceKind::Edge,
            stable_id: missing.to_string(),
            ordered_index: Some(index),
        }));
        return Err(error);
    }
    Solid::try_new(boundaries).map_err(|error| {
        unsupported_preserving(
            format!("pinned edge treatment produced an invalid solid: {error}"),
            "target",
            &input.target,
            None,
        )
    })
}

#[derive(Debug, Clone, Copy)]
struct ShellFrame {
    bounds: AxisAlignedBoundsNm,
    removed_axis: usize,
    removed_positive: bool,
}

#[derive(Debug, Clone, Copy)]
struct DirectedAxis {
    axis: usize,
    positive: bool,
}

/// Build an exact closed-manifold cup from one axis-aligned rectangular prism.
/// This is a real boundary representation with shared edges: five outer faces,
/// five cavity faces, and four opening-rim faces. Unsupported topology never
/// falls back to a mesh or bounding-box approximation.
fn execute_shell(input: &ShellInput) -> Result<Solid, FeatureError> {
    let source = decode_solid("target", &input.target)?;
    let frame = qualified_shell_frame(input, &source)?;
    let [u_axis, v_axis, w_axis] = shell_basis(frame);
    let span = |axis: DirectedAxis| frame.bounds.max[axis.axis] - frame.bounds.min[axis.axis];
    let [du, dv, dw] = [span(u_axis), span(v_axis), span(w_axis)];
    let thickness = input.wall_thickness_nm;
    if thickness
        .checked_mul(2)
        .is_none_or(|twice| twice >= du || twice >= dv)
        || thickness >= dw
    {
        return Err(shell_input_error(
            input,
            ErrorCategory::InvalidInput,
            "wall_thickness_nm",
            "wall thickness leaves no positive interior cavity",
            "reduce Wall thickness below half of both face dimensions and below the body depth",
        ));
    }

    let local = [
        [0, 0, 0],
        [du, 0, 0],
        [du, dv, 0],
        [0, dv, 0],
        [0, 0, dw],
        [du, 0, dw],
        [du, dv, dw],
        [0, dv, dw],
        [thickness, thickness, thickness],
        [du - thickness, thickness, thickness],
        [du - thickness, dv - thickness, thickness],
        [thickness, dv - thickness, thickness],
        [thickness, thickness, dw],
        [du - thickness, thickness, dw],
        [du - thickness, dv - thickness, dw],
        [thickness, dv - thickness, dw],
    ];
    let vertices: Vec<Vertex> = local
        .into_iter()
        .map(|point| {
            builder::vertex(shell_world_point(
                frame.bounds,
                [u_axis, v_axis, w_axis],
                point,
            ))
        })
        .collect();
    // Every loop is counter-clockwise from the material exterior. Reusing the
    // same edge object in opposite directions makes the result an oriented,
    // closed, non-singular shell instead of a collection of coincident faces.
    let loops = [
        [0, 3, 2, 1],
        [0, 1, 5, 4],
        [1, 2, 6, 5],
        [2, 3, 7, 6],
        [3, 0, 4, 7],
        [8, 9, 10, 11],
        [8, 12, 13, 9],
        [9, 13, 14, 10],
        [10, 14, 15, 11],
        [11, 15, 12, 8],
        [4, 5, 13, 12],
        [5, 6, 14, 13],
        [6, 7, 15, 14],
        [7, 4, 12, 15],
    ];
    let mut edges = BTreeMap::new();
    let faces = loops
        .into_iter()
        .map(|indices| shell_planar_face(&vertices, &mut edges, indices, input))
        .collect::<Result<Vec<_>, _>>()?;
    let shell: Shell = faces.into_iter().collect();
    Solid::try_new(vec![shell]).map_err(|error| {
        shell_input_error(
            input,
            ErrorCategory::Unsupported,
            "target",
            format!("qualified prismatic Shell produced an invalid boundary: {error}"),
            "repair the source body or choose another planar box face",
        )
    })
}

fn exact_shell_volume(input: &ShellInput) -> Result<f64, FeatureError> {
    let source = decode_solid("target", &input.target)?;
    let frame = qualified_shell_frame(input, &source)?;
    let [u_axis, v_axis, w_axis] = shell_basis(frame);
    let span =
        |axis: DirectedAxis| model_units(frame.bounds.max[axis.axis] - frame.bounds.min[axis.axis]);
    let [du, dv, dw] = [span(u_axis), span(v_axis), span(w_axis)];
    let thickness = model_units(input.wall_thickness_nm);
    Ok(du * dv * dw - (du - 2.0 * thickness) * (dv - 2.0 * thickness) * (dw - thickness))
}

fn qualified_shell_frame(input: &ShellInput, solid: &Solid) -> Result<ShellFrame, FeatureError> {
    if solid.boundaries().len() != 1 || solid.face_iter().count() != 6 {
        return Err(shell_input_error(
            input,
            ErrorCategory::Unsupported,
            "target",
            "Shell currently requires one six-face axis-aligned rectangular prism",
            "select an unmodified rectangular-prism body",
        ));
    }
    let points = solid
        .vertex_iter()
        .map(|vertex| point_nm(vertex.point()))
        .collect::<Result<BTreeSet<_>, _>>()?;
    let bounds = bounds_nm(
        &solid
            .vertex_iter()
            .map(|vertex| vertex.point())
            .collect::<Vec<_>>(),
    )?;
    let expected = (0..8)
        .map(|corner| {
            std::array::from_fn(|axis| {
                if corner & (1 << axis) == 0 {
                    bounds.min[axis]
                } else {
                    bounds.max[axis]
                }
            })
        })
        .collect::<BTreeSet<[i64; 3]>>();
    if points != expected || (0..3).any(|axis| bounds.min[axis] >= bounds.max[axis]) {
        return Err(shell_input_error(
            input,
            ErrorCategory::Unsupported,
            "target",
            "Shell source is not an exact axis-aligned rectangular prism",
            "select an unmodified rectangular-prism body",
        ));
    }

    let selected_id = input.removed_face_stable_ids[0];
    let selected = solid
        .face_iter()
        .find(|face| face.stable_id().raw() == selected_id)
        .ok_or_else(|| {
            shell_reference_error(
                input,
                ErrorCategory::InvalidInput,
                "removed_face_stable_ids",
                "selected face reference is absent from the target",
                "select one current outer face and retry",
            )
        })?;
    let face_points = selected
        .vertex_iter()
        .map(|vertex| point_nm(vertex.point()))
        .collect::<Result<BTreeSet<_>, _>>()?;
    if face_points.len() != 4 {
        return Err(shell_reference_error(
            input,
            ErrorCategory::Unsupported,
            "removed_face_stable_ids",
            "selected face is not a rectangular outer face",
            "select one planar rectangular-prism face",
        ));
    }
    let candidates = (0..3)
        .filter_map(|axis| {
            let coordinate = face_points.first().expect("validated face points")[axis];
            face_points
                .iter()
                .all(|point| point[axis] == coordinate)
                .then_some((axis, coordinate))
        })
        .collect::<Vec<_>>();
    if candidates.len() != 1 {
        return Err(shell_reference_error(
            input,
            ErrorCategory::Unsupported,
            "removed_face_stable_ids",
            "selected face has no unique principal normal",
            "select one axis-aligned rectangular-prism face",
        ));
    }
    let (removed_axis, coordinate) = candidates[0];
    let removed_positive = if coordinate == bounds.max[removed_axis] {
        true
    } else if coordinate == bounds.min[removed_axis] {
        false
    } else {
        return Err(shell_reference_error(
            input,
            ErrorCategory::Unsupported,
            "removed_face_stable_ids",
            "selected face is not on the source body's outer bound",
            "select one outer rectangular-prism face",
        ));
    };
    for axis in (0..3).filter(|axis| *axis != removed_axis) {
        let coordinates = face_points
            .iter()
            .map(|point| point[axis])
            .collect::<BTreeSet<_>>();
        if coordinates != BTreeSet::from([bounds.min[axis], bounds.max[axis]]) {
            return Err(shell_reference_error(
                input,
                ErrorCategory::Unsupported,
                "removed_face_stable_ids",
                "selected face does not span the source body's outer bounds",
                "select one outer rectangular-prism face",
            ));
        }
    }
    Ok(ShellFrame {
        bounds,
        removed_axis,
        removed_positive,
    })
}

fn shell_basis(frame: ShellFrame) -> [DirectedAxis; 3] {
    let positive = |axis| DirectedAxis {
        axis,
        positive: true,
    };
    let negative = |axis| DirectedAxis {
        axis,
        positive: false,
    };
    match (frame.removed_axis, frame.removed_positive) {
        (2, true) => [positive(0), positive(1), positive(2)],
        (2, false) => [positive(0), negative(1), negative(2)],
        (0, true) => [positive(1), positive(2), positive(0)],
        (0, false) => [positive(1), negative(2), negative(0)],
        (1, true) => [positive(2), positive(0), positive(1)],
        (1, false) => [positive(2), negative(0), negative(1)],
        _ => unreachable!("principal axis is bounded by validation"),
    }
}

fn shell_world_point(
    bounds: AxisAlignedBoundsNm,
    basis: [DirectedAxis; 3],
    local_nm: [i64; 3],
) -> Point3 {
    let mut world_nm = [0; 3];
    for (coordinate, axis) in local_nm.into_iter().zip(basis) {
        world_nm[axis.axis] = if axis.positive {
            bounds.min[axis.axis] + coordinate
        } else {
            bounds.max[axis.axis] - coordinate
        };
    }
    point_from_nm(world_nm)
}

fn shell_planar_face(
    vertices: &[Vertex],
    edges: &mut BTreeMap<(usize, usize), Edge>,
    indices: [usize; 4],
    input: &ShellInput,
) -> Result<Face, FeatureError> {
    let mut oriented = Vec::with_capacity(4);
    for index in 0..4 {
        let front = indices[index];
        let back = indices[(index + 1) % 4];
        let key = if front < back {
            (front, back)
        } else {
            (back, front)
        };
        let edge = edges
            .entry(key)
            .or_insert_with(|| builder::line(&vertices[key.0], &vertices[key.1]));
        oriented.push(if front < back {
            edge.clone()
        } else {
            edge.inverse()
        });
    }
    builder::try_attach_plane(vec![Wire::from(oriented)]).map_err(|error| {
        shell_input_error(
            input,
            ErrorCategory::Unsupported,
            "target",
            format!("cannot construct an exact planar Shell boundary: {error}"),
            "repair the source body or choose another planar box face",
        )
    })
}

fn shell_reference_error(
    input: &ShellInput,
    category: ErrorCategory,
    field: &str,
    message: impl Into<String>,
    recovery: impl Into<String>,
) -> FeatureError {
    let mut error = shell_input_error(input, category, field, message, recovery);
    error.problematic_reference = Some(Box::new(ProblematicReference {
        kind: ReferenceKind::Face,
        stable_id: input.removed_face_stable_ids[0].to_string(),
        ordered_index: Some(0),
    }));
    error
}

fn shell_input_error(
    input: &ShellInput,
    category: ErrorCategory,
    field: &str,
    message: impl Into<String>,
    recovery: impl Into<String>,
) -> FeatureError {
    let mut error = failure(category, message, Some(field), recovery);
    error.preserved_inputs.push(input.target.clone());
    error
}

fn execute_draft(input: &DraftInput) -> Result<Solid, FeatureError> {
    let source = decode_solid("target", &input.target).map_err(|mut error| {
        error.preserved_inputs.push(input.target.clone());
        error
    })?;
    let boxes = qualified_axis_aligned_boxes(&source)?.ok_or_else(|| {
        draft_error(
            input,
            ErrorCategory::Unsupported,
            "target",
            "Draft requires one exact axis-aligned rectangular-prism body",
            None,
        )
    })?;
    if boxes.len() != 1 || source.boundaries().len() != 1 {
        return Err(draft_error(
            input,
            ErrorCategory::Unsupported,
            "target",
            "Draft requires exactly one rectangular-prism boundary",
            None,
        ));
    }
    let bounds = AxisAlignedBoundsNm {
        min: boxes[0].min,
        max: boxes[0].max,
    };
    let pull_axis = principal_axis_index(input.pull_direction);
    let neutral = input.neutral_plane_origin_nm[pull_axis];
    if neutral < bounds.min[pull_axis] || neutral > bounds.max[pull_axis] {
        return Err(draft_error(
            input,
            ErrorCategory::InvalidInput,
            "neutral_plane_origin_nm",
            "neutral plane must intersect the source prism along the pull direction",
            None,
        ));
    }

    let mut selected_planes = BTreeSet::new();
    for (ordered_index, stable_id) in input.face_stable_ids.iter().copied().enumerate() {
        let face = source
            .face_iter()
            .find(|face| face.stable_id().raw() == stable_id)
            .ok_or_else(|| {
                draft_error(
                    input,
                    ErrorCategory::InvalidInput,
                    "face_stable_ids",
                    "contains a reference absent from the target",
                    Some((stable_id, ordered_index)),
                )
            })?;
        let points = face
            .vertex_iter()
            .map(|vertex| point_nm(vertex.point()))
            .collect::<Result<BTreeSet<_>, _>>()?;
        let constant = (0..3)
            .filter_map(|axis| {
                let coordinate = points.first()?[axis];
                points
                    .iter()
                    .all(|point| point[axis] == coordinate)
                    .then_some((axis, coordinate))
            })
            .collect::<Vec<_>>();
        if constant.len() != 1 {
            return Err(draft_error(
                input,
                ErrorCategory::Unsupported,
                "face_stable_ids",
                "selected face is not planar on one principal plane",
                Some((stable_id, ordered_index)),
            ));
        }
        let (axis, coordinate) = constant[0];
        if axis == pull_axis {
            return Err(draft_error(
                input,
                ErrorCategory::InvalidInput,
                "face_stable_ids",
                "selected face must be parallel to the pull direction",
                Some((stable_id, ordered_index)),
            ));
        }
        let positive = if coordinate == bounds.max[axis] {
            true
        } else if coordinate == bounds.min[axis] {
            false
        } else {
            return Err(draft_error(
                input,
                ErrorCategory::Unsupported,
                "face_stable_ids",
                "selected face does not lie on the prism's outer bounds",
                Some((stable_id, ordered_index)),
            ));
        };
        selected_planes.insert((axis, positive));
    }

    let angle = input.angle_microdegrees as f64 / MICRODEGREES_PER_REVOLUTION as f64 * TAU;
    let tangent = angle.tan();
    let section = |coordinate: i64| -> Result<Vec<[i64; 3]>, FeatureError> {
        let delta = ((coordinate - neutral) as f64 * tangent).round();
        if !delta.is_finite() || delta.abs() > MAX_EXACT_NANOMETERS as f64 {
            return Err(draft_error(
                input,
                ErrorCategory::Numerical,
                "angle_microdegrees",
                "draft displacement exceeds exact nanometer range",
                None,
            ));
        }
        let delta = delta as i64;
        let mut min = bounds.min;
        let mut max = bounds.max;
        for &(axis, positive) in &selected_planes {
            if positive {
                max[axis] = max[axis].checked_add(delta).ok_or_else(|| {
                    draft_error(
                        input,
                        ErrorCategory::Numerical,
                        "angle_microdegrees",
                        "draft displacement overflowed exact coordinates",
                        None,
                    )
                })?;
            } else {
                min[axis] = min[axis].checked_sub(delta).ok_or_else(|| {
                    draft_error(
                        input,
                        ErrorCategory::Numerical,
                        "angle_microdegrees",
                        "draft displacement overflowed exact coordinates",
                        None,
                    )
                })?;
            }
        }
        if (0..3)
            .filter(|axis| *axis != pull_axis)
            .any(|axis| min[axis] >= max[axis])
        {
            return Err(draft_error(
                input,
                ErrorCategory::InvalidInput,
                "angle_microdegrees",
                "draft collapses or inverts a prism section",
                None,
            ));
        }
        Ok(rectangular_section(min, max, pull_axis, coordinate))
    };
    let profiles_nm = vec![
        section(bounds.min[pull_axis])?,
        section(bounds.max[pull_axis])?,
    ];
    if profiles_nm[0] == profiles_nm[1] {
        return Err(draft_error(
            input,
            ErrorCategory::InvalidInput,
            "angle_microdegrees",
            "draft angle rounds to zero displacement at model precision",
            None,
        ));
    }
    execute_loft(&LoftInput {
        profiles_nm,
        tolerance_nm: input.tolerance_nm,
    })
    .map_err(|error| {
        draft_error(
            input,
            error.category,
            error.field.as_deref().unwrap_or("target"),
            format!(
                "draft could not construct a valid tapered prism: {}",
                error.message
            ),
            None,
        )
    })
}

fn rectangular_section(
    min: [i64; 3],
    max: [i64; 3],
    pull_axis: usize,
    coordinate: i64,
) -> Vec<[i64; 3]> {
    match pull_axis {
        0 => vec![
            [coordinate, min[1], min[2]],
            [coordinate, max[1], min[2]],
            [coordinate, max[1], max[2]],
            [coordinate, min[1], max[2]],
        ],
        1 => vec![
            [min[0], coordinate, min[2]],
            [min[0], coordinate, max[2]],
            [max[0], coordinate, max[2]],
            [max[0], coordinate, min[2]],
        ],
        2 => vec![
            [min[0], min[1], coordinate],
            [max[0], min[1], coordinate],
            [max[0], max[1], coordinate],
            [min[0], max[1], coordinate],
        ],
        _ => unreachable!("principal axis index"),
    }
}

fn principal_axis_index(axis: PrincipalAxis) -> usize {
    match axis {
        PrincipalAxis::X => 0,
        PrincipalAxis::Y => 1,
        PrincipalAxis::Z => 2,
    }
}

fn draft_error(
    input: &DraftInput,
    category: ErrorCategory,
    field: &str,
    message: impl Into<String>,
    reference: Option<(u64, usize)>,
) -> FeatureError {
    let mut error = failure(
        category,
        message,
        Some(field),
        "retain the original body and choose qualified planar prism side faces",
    );
    error.preserved_inputs.push(input.target.clone());
    error.problematic_reference = reference.map(|(stable_id, ordered_index)| {
        Box::new(ProblematicReference {
            kind: ReferenceKind::Face,
            stable_id: stable_id.to_string(),
            ordered_index: Some(ordered_index),
        })
    });
    error
}

fn point_nm(point: Point3) -> Result<[i64; 3], FeatureError> {
    Ok([
        model_coordinate_nm(point[0])?,
        model_coordinate_nm(point[1])?,
        model_coordinate_nm(point[2])?,
    ])
}

fn resolve_transform_source(source: &TransformSource) -> Result<&BodySnapshot, FeatureError> {
    match source {
        TransformSource::Body { body } => Ok(body),
        TransformSource::FeatureSequence {
            ordered_feature_ids,
            resolved_body,
        } => Err(unsupported_preserving(
            "feature-sequence transforms require feature-graph re-evaluation; the body kernel will not substitute a body transform",
            "source.ordered_feature_ids",
            resolved_body,
            ordered_feature_ids.first().map(|id| ProblematicReference {
                kind: ReferenceKind::Feature,
                stable_id: id.clone(),
                ordered_index: Some(0),
            }),
        )),
    }
}

fn execute_mirror(input: &MirrorInput, body: &BodySnapshot) -> Result<Solid, FeatureError> {
    let source = decode_solid("source.body", body)?;
    let scalars = match input.plane_normal {
        PrincipalAxis::X => Vector3::new(-1.0, 1.0, 1.0),
        PrincipalAxis::Y => Vector3::new(1.0, -1.0, 1.0),
        PrincipalAxis::Z => Vector3::new(1.0, 1.0, -1.0),
    };
    let mut mirrored = builder::scaled(&source, point_from_nm(input.plane_origin_nm), scalars);
    mirrored.not();
    Ok(mirrored)
}

fn execute_transform(input: &TransformInput, body: &BodySnapshot) -> Result<Solid, FeatureError> {
    let source = decode_solid("source.body", body)?;
    Ok(builder::translated(
        &source,
        Vector3::new(
            model_units(input.translation_nm[0]),
            model_units(input.translation_nm[1]),
            model_units(input.translation_nm[2]),
        ),
    ))
}

fn execute_linear_pattern(
    input: &LinearPatternInput,
    body: &BodySnapshot,
) -> Result<Solid, FeatureError> {
    let source = decode_solid("source.body", body)?;
    let step = Vector3::new(
        model_units(input.step_nm[0]),
        model_units(input.step_nm[1]),
        model_units(input.step_nm[2]),
    );
    let instances = (0..input.instance_body_ids.len())
        .map(|index| builder::translated(&source, step * index as f64));
    compound_instances(instances, body, "linear pattern")
}

fn execute_circular_pattern(
    input: &CircularPatternInput,
    body: &BodySnapshot,
) -> Result<Solid, FeatureError> {
    let source = decode_solid("source.body", body)?;
    let origin = point_from_nm(input.axis_origin_nm);
    let axis = match input.axis {
        PrincipalAxis::X => Vector3::unit_x(),
        PrincipalAxis::Y => Vector3::unit_y(),
        PrincipalAxis::Z => Vector3::unit_z(),
    };
    let step = input.step_microdegrees as f64 / MICRODEGREES_PER_REVOLUTION as f64 * TAU;
    let instances = (0..input.instance_body_ids.len()).map(|index| {
        builder::rotated(
            &source,
            origin,
            axis,
            monstertruck_modeling::Rad(step * index as f64),
        )
    });
    compound_instances(instances, body, "circular pattern")
}

fn compound_instances(
    instances: impl Iterator<Item = Solid>,
    source: &BodySnapshot,
    operation: &str,
) -> Result<Solid, FeatureError> {
    let boundaries = instances.flat_map(Solid::into_boundaries).collect();
    Solid::try_new(boundaries).map_err(|error| {
        unsupported_preserving(
            format!("pinned transform kernel rejected {operation}: {error}"),
            "source.body",
            source,
            None,
        )
    })
}

fn decode_solid(field: &str, snapshot: &BodySnapshot) -> Result<Solid, FeatureError> {
    serde_json::from_slice(&snapshot.solid_json).map_err(|error| {
        failure(
            ErrorCategory::InvalidInput,
            format!("{field} is not a serialized Monstertruck solid: {error}"),
            Some(field),
            "reload or rebuild the referenced body",
        )
    })
}

#[cfg(not(target_arch = "wasm32"))]
fn map_boolean_error(error: ShapeOpsError, tool_index: usize) -> FeatureError {
    let field = format!("tools[{tool_index}]");
    match error {
        ShapeOpsError::InvalidTolerance => invalid("tolerance_nm", "kernel rejected tolerance"),
        ShapeOpsError::NoBackend => failure(
            ErrorCategory::Unsupported,
            error.to_string(),
            Some("operation"),
            "enable the pinned marching-ssi backend before executing booleans",
        ),
        ShapeOpsError::EmptyOutputShell { .. } => failure(
            ErrorCategory::EmptyResult,
            error.to_string(),
            Some(&field),
            "edit the ordered tool so the boolean has non-empty volume",
        ),
        other => failure(
            ErrorCategory::Unsupported,
            format!("pinned boolean kernel rejected {field}: {other}"),
            Some(&field),
            "simplify the operands or adjust the explicit tolerance",
        ),
    }
}

fn geometry_evidence(
    solid: &Solid,
    tolerance_nm: i64,
    request: &FeatureRequest,
) -> Result<GeometryEvidence, FeatureError> {
    let points: Vec<Point3> = solid.vertex_iter().map(|vertex| vertex.point()).collect();
    let bounds = bounds_nm(&points)?;
    let tolerance = model_units(tolerance_nm);
    let volume = if let FeatureOperation::Shell(input) = &request.operation {
        exact_shell_volume(input)?
    } else {
        #[cfg(not(target_arch = "wasm32"))]
        {
            solid.triangulation(tolerance).to_polygon().volume().abs()
        }
        #[cfg(target_arch = "wasm32")]
        {
            let mut sampled = solid.clone();
            let packet = crawler_render_packet::packet_from_solid(&mut sampled, tolerance)
                .map_err(|error| {
                    failure(
                        ErrorCategory::Numerical,
                        format!("Crawler WASM sampler rejected kernel body: {error}"),
                        Some("tolerance_nm"),
                        "adjust tolerance or simplify the feature geometry",
                    )
                })?;
            sampled_packet_volume(&packet).max(bounds_volume(bounds))
        }
    };
    if !volume.is_finite() {
        return Err(failure(
            ErrorCategory::Numerical,
            "kernel produced a non-finite volume",
            Some("tolerance_nm"),
            "increase tolerance or reduce model dimensions",
        ));
    }
    if volume <= f64::EPSILON {
        return Err(failure(
            ErrorCategory::EmptyResult,
            "operation produced zero measurable volume",
            None,
            "edit the feature so the result has non-zero volume",
        ));
    }
    let vertex_count = solid.vertex_iter().count();
    let edge_count = solid.edge_iter().count();
    let face_count = solid.face_iter().count();
    let canonical = serde_json::to_vec(&(
        request,
        vertex_count,
        edge_count,
        face_count,
        bounds,
        volume.to_bits(),
    ))
    .map_err(|error| {
        failure(
            ErrorCategory::Unsupported,
            format!("cannot canonicalize feature evidence: {error}"),
            None,
            "simplify the feature DTO",
        )
    })?;
    Ok(GeometryEvidence {
        vertex_count,
        edge_count,
        face_count,
        bounds_nm: bounds,
        volume_model_units3: volume,
        deterministic_digest: format!("fnv1a64:{:016x}", fnv1a64(&canonical)),
    })
}

#[cfg(target_arch = "wasm32")]
fn sampled_packet_volume(packet: &crawler_render_packet::RenderPacket) -> f64 {
    packet
        .triangle_indices
        .chunks_exact(3)
        .map(|triangle| {
            let point = |index: u32| {
                let offset = index as usize * 3;
                [
                    packet.positions[offset] as f64,
                    packet.positions[offset + 1] as f64,
                    packet.positions[offset + 2] as f64,
                ]
            };
            let a = point(triangle[0]);
            let b = point(triangle[1]);
            let c = point(triangle[2]);
            (a[0] * (b[1] * c[2] - b[2] * c[1])
                + a[1] * (b[2] * c[0] - b[0] * c[2])
                + a[2] * (b[0] * c[1] - b[1] * c[0]))
                / 6.0
        })
        .sum::<f64>()
        .abs()
}

#[cfg(target_arch = "wasm32")]
fn bounds_volume(bounds: AxisAlignedBoundsNm) -> f64 {
    bounds
        .min
        .into_iter()
        .zip(bounds.max)
        .map(|(min, max)| (max - min).max(0) as f64 / NANOMETERS_PER_MODEL_UNIT)
        .product::<f64>()
        * f64::EPSILON
}

fn closed_wire(points: [Point3; 4]) -> Wire {
    let vertices = points.map(builder::vertex);
    vec![
        builder::line(&vertices[0], &vertices[1]),
        builder::line(&vertices[1], &vertices[2]),
        builder::line(&vertices[2], &vertices[3]),
        builder::line(&vertices[3], &vertices[0]),
    ]
    .into()
}

fn polygon_wire(points: &[[i64; 3]]) -> Wire {
    polygon_wire_points(
        &points
            .iter()
            .copied()
            .map(point_from_nm)
            .collect::<Vec<_>>(),
    )
}

fn polygon_wire_points(points: &[Point3]) -> Wire {
    let vertices = points
        .iter()
        .copied()
        .map(builder::vertex)
        .collect::<Vec<_>>();
    (0..vertices.len())
        .map(|index| builder::line(&vertices[index], &vertices[(index + 1) % vertices.len()]))
        .collect::<Vec<_>>()
        .into()
}

fn capped_skin(wires: &[Wire], operation: &str, field: &str) -> Result<Solid, FeatureError> {
    let mut shell: Shell = builder::try_skin_wires(wires).map_err(|error| {
        failure(
            ErrorCategory::InvalidInput,
            format!("{operation} section correspondence is invalid: {error}"),
            Some(field),
            "use valid closed polygon sections with consistent caller-owned winding",
        )
    })?;
    let boundaries = shell.extract_boundaries();
    if boundaries.len() != 2 {
        return Err(failure(
            ErrorCategory::InvalidInput,
            format!("{operation} produced {} open boundaries", boundaries.len()),
            Some(field),
            "remove self-intersections and keep sections in consistent order",
        ));
    }
    for boundary in boundaries {
        let cap = builder::try_attach_plane(vec![boundary.inverse()]).map_err(|error| {
            failure(
                ErrorCategory::InvalidInput,
                format!("{operation} cap is invalid: {error}"),
                Some(field),
                "use closed coplanar polygon sections",
            )
        })?;
        shell.push(cap);
    }
    Solid::try_new(vec![shell]).map_err(|error| {
        failure(
            ErrorCategory::InvalidInput,
            format!("{operation} produced an invalid boundary representation: {error}"),
            Some(field),
            "remove section crossings and keep section winding consistent",
        )
    })
}

/// Union of normalized vertex positions preserves every caller-supplied
/// polygon corner while giving every loft section identical edge counts.
fn profile_breakpoints(profiles: &[Vec<[i64; 3]>]) -> Vec<f64> {
    let mut breaks = Vec::new();
    for profile in profiles {
        let lengths = polygon_edge_lengths(profile);
        let total = lengths.iter().sum::<f64>();
        let mut accumulated = 0.0;
        for length in lengths {
            breaks.push(accumulated / total);
            accumulated += length;
        }
    }
    breaks.sort_by(f64::total_cmp);
    breaks.dedup_by(|left, right| (*left - *right).abs() <= 1.0e-12);
    breaks
}

fn polygon_edge_lengths(points: &[[i64; 3]]) -> Vec<f64> {
    (0..points.len())
        .map(|index| {
            vector_between_nm(points[index], points[(index + 1) % points.len()]).magnitude()
        })
        .collect()
}

fn resample_polygon(points: &[[i64; 3]], breaks: &[f64]) -> Vec<Point3> {
    let lengths = polygon_edge_lengths(points);
    let total = lengths.iter().sum::<f64>();
    breaks
        .iter()
        .copied()
        .map(|position| {
            let target = position * total;
            let mut accumulated = 0.0;
            for (index, length) in lengths.iter().copied().enumerate() {
                if target <= accumulated + length || index + 1 == lengths.len() {
                    let ratio = ((target - accumulated) / length).clamp(0.0, 1.0);
                    let front = point_from_nm(points[index]);
                    let delta =
                        vector_between_nm(points[index], points[(index + 1) % points.len()]);
                    return front + delta * ratio;
                }
                accumulated += length;
            }
            unreachable!("non-empty validated polygon")
        })
        .collect()
}

fn polygon_normal(points: &[[i64; 3]]) -> Option<Vector3> {
    let mut normal = Vector3::new(0.0, 0.0, 0.0);
    for index in 0..points.len() {
        let current = point_from_nm(points[index]);
        let next = point_from_nm(points[(index + 1) % points.len()]);
        normal.x += (current.y - next.y) * (current.z + next.z);
        normal.y += (current.z - next.z) * (current.x + next.x);
        normal.z += (current.x - next.x) * (current.y + next.y);
    }
    let magnitude = normal.magnitude();
    (magnitude > f64::EPSILON).then(|| normal / magnitude)
}

fn vector_from_nm(value: [i64; 3]) -> Vector3 {
    Vector3::new(
        model_units(value[0]),
        model_units(value[1]),
        model_units(value[2]),
    )
}

fn vector_between_nm(front: [i64; 3], back: [i64; 3]) -> Vector3 {
    Vector3::new(
        model_units(back[0] - front[0]),
        model_units(back[1] - front[1]),
        model_units(back[2] - front[2]),
    )
}

fn bounds_nm(points: &[Point3]) -> Result<AxisAlignedBoundsNm, FeatureError> {
    if points.is_empty() {
        return Err(failure(
            ErrorCategory::EmptyResult,
            "solid has no vertices",
            None,
            "edit the feature so it creates a bounded solid",
        ));
    }
    let mut min = [f64::INFINITY; 3];
    let mut max = [f64::NEG_INFINITY; 3];
    for point in points {
        for axis in 0..3 {
            min[axis] = min[axis].min(point[axis]);
            max[axis] = max[axis].max(point[axis]);
        }
    }
    Ok(AxisAlignedBoundsNm {
        min: [
            model_coordinate_nm(min[0])?,
            model_coordinate_nm(min[1])?,
            model_coordinate_nm(min[2])?,
        ],
        max: [
            model_coordinate_nm(max[0])?,
            model_coordinate_nm(max[1])?,
            model_coordinate_nm(max[2])?,
        ],
    })
}

fn model_coordinate_nm(value: f64) -> Result<i64, FeatureError> {
    let nm = value * NANOMETERS_PER_MODEL_UNIT;
    if !nm.is_finite() || nm.abs() > MAX_EXACT_NANOMETERS as f64 {
        return Err(failure(
            ErrorCategory::Numerical,
            "geometry bounds exceed exact nanometer range",
            None,
            "reduce model dimensions",
        ));
    }
    Ok(nm.round() as i64)
}

fn point_from_nm(value: [i64; 3]) -> Point3 {
    Point3::new(
        model_units(value[0]),
        model_units(value[1]),
        model_units(value[2]),
    )
}

fn model_units(value: i64) -> f64 {
    value as f64 / NANOMETERS_PER_MODEL_UNIT
}

fn exact_nm(field: &str, value: i64) -> Result<(), FeatureError> {
    if value.unsigned_abs() > MAX_EXACT_NANOMETERS as u64 {
        return Err(failure(
            ErrorCategory::Numerical,
            format!("{field} exceeds exact nanometer range"),
            Some(field),
            "reduce the absolute value to 9007199254740991 nanometers or less",
        ));
    }
    Ok(())
}

fn exact_positive_nm(field: &str, value: i64) -> Result<(), FeatureError> {
    exact_nm(field, value)?;
    if value <= 0 {
        return Err(invalid(field, "must be an integer greater than zero"));
    }
    Ok(())
}

fn invalid(field: &str, detail: &str) -> FeatureError {
    failure(
        ErrorCategory::InvalidInput,
        format!("{field} {detail}"),
        Some(field),
        "edit the typed feature input and retry",
    )
}

fn failure(
    category: ErrorCategory,
    message: impl Into<String>,
    field: Option<&str>,
    recovery: impl Into<String>,
) -> FeatureError {
    FeatureError {
        category,
        message: message.into(),
        field: field.map(str::to_owned),
        recovery: recovery.into(),
        preserved_inputs: Vec::new(),
        problematic_reference: None,
    }
}

fn unsupported_preserving(
    message: impl Into<String>,
    field: &str,
    input: &BodySnapshot,
    problematic_reference: Option<ProblematicReference>,
) -> FeatureError {
    FeatureError {
        category: ErrorCategory::Unsupported,
        message: message.into(),
        field: Some(field.to_owned()),
        recovery: "retain the original input and choose a qualified operation".to_owned(),
        preserved_inputs: vec![input.clone()],
        problematic_reference: problematic_reference.map(Box::new),
    }
}

fn fnv1a64(bytes: &[u8]) -> u64 {
    bytes.iter().fold(0xcbf29ce484222325, |hash, byte| {
        (hash ^ u64::from(*byte)).wrapping_mul(0x100000001b3)
    })
}

#[cfg(test)]
mod qualified_box_boolean_tests {
    use super::*;

    fn box_solid(min: [i64; 3], max: [i64; 3]) -> Solid {
        let vertex = builder::vertex(point_from_nm(min));
        let edge = builder::extrude(&vertex, Vector3::unit_x() * model_units(max[0] - min[0]));
        let face = builder::extrude(&edge, Vector3::unit_y() * model_units(max[1] - min[1]));
        builder::extrude(&face, Vector3::unit_z() * model_units(max[2] - min[2]))
    }

    fn qualified_box(min: [i64; 3], max: [i64; 3]) -> QualifiedBoxNm {
        QualifiedBoxNm { min, max }
    }

    #[test]
    fn overlapping_non_identical_boxes_have_exact_boolean_volumes() {
        let target = qualified_box([0, 0, 0], [2_000_000, 2_000_000, 2_000_000]);
        let tool = qualified_box(
            [1_000_000, 1_000_000, 1_000_000],
            [3_000_000, 3_000_000, 3_000_000],
        );
        for (operation, expected_volume) in [
            (BooleanKind::Union, 15.0),
            (BooleanKind::Cut, 7.0),
            (BooleanKind::Intersect, 1.0),
        ] {
            let cells = orthogonal_boolean_cells(&[target], &[tool], operation).unwrap();
            let solid = solid_from_orthogonal_cells(&cells).unwrap();
            let volume = solid.triangulation(0.01).to_polygon().volume().abs();
            assert!(
                (volume - expected_volume).abs() < 1.0e-9,
                "{operation:?}: actual={volume}, expected={expected_volume}"
            );
        }
    }

    #[test]
    fn qualified_box_output_is_deterministic_and_recognizes_import_style_duplicates() {
        let target = box_solid([0, 0, 0], [2_000_000, 2_000_000, 2_000_000]);
        let boxes = qualified_axis_aligned_boxes(&target).unwrap().unwrap();
        assert_eq!(
            boxes,
            [qualified_box([0, 0, 0], [2_000_000, 2_000_000, 2_000_000])]
        );
        let tool = qualified_box(
            [1_000_000, 1_000_000, 1_000_000],
            [3_000_000, 3_000_000, 3_000_000],
        );
        let first = orthogonal_boolean_cells(&boxes, &[tool], BooleanKind::Union).unwrap();
        let second = orthogonal_boolean_cells(&boxes, &[tool], BooleanKind::Union).unwrap();
        assert_eq!(first, second);
        assert_eq!(
            serde_json::to_vec(&solid_from_orthogonal_cells(&first).unwrap()).unwrap(),
            serde_json::to_vec(&solid_from_orthogonal_cells(&second).unwrap()).unwrap()
        );
    }

    #[test]
    fn non_prismatic_topology_does_not_qualify() {
        let input = RevolveInput {
            axis_origin_nm: [0, 0, 0],
            axis: PrincipalAxis::Z,
            inner_radius_nm: 0,
            outer_radius_nm: 1_000_000,
            axial_start_nm: 0,
            axial_end_nm: 2_000_000,
            sweep_microdegrees: MICRODEGREES_PER_REVOLUTION,
            divisions: 8,
            tolerance_nm: 10_000,
        };
        let revolved = execute_revolve(&input).unwrap();
        assert!(qualified_axis_aligned_boxes(&revolved).unwrap().is_none());
    }
}
