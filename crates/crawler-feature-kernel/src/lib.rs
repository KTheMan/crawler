#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct FeatureRequest {
    pub schema_version: u16,
    pub document_id: String,
    pub feature_id: String,
    pub output_body_id: String,
    pub operation: FeatureOperation,
}

